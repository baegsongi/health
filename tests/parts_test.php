<?php
declare(strict_types=1);

use Health\Parts;

T::group('부위 분류 (문서 §2.6)');

T::is(Parts::of('스쿼트'), ['하체'], '스쿼트 → 하체');
T::is(Parts::of('렛 풀 다운'), ['등'], '렛 풀 다운 → 등');
T::is(Parts::of('벤치 프레스'), ['가슴'], '벤치 프레스 → 가슴');
T::is(Parts::of('숄더 프레스'), ['어깨'], '숄더 프레스 → 어깨');
T::is(Parts::of('트라이셉스 킥 백'), ['팔'], '트라이셉스 킥 백 → 팔');
T::is(Parts::of('러시안 트위스트'), ['코어'], '러시안 트위스트 → 코어');
T::is(Parts::of('버피'), ['전신'], '버피 → 전신');

// 유산소 · 전신
T::is(Parts::of('러닝'), ['유산소'], '러닝 → 유산소');
T::is(Parts::of('천국의 계단'), ['유산소'], '천국의 계단 → 유산소');
T::is(Parts::of('천국의계단'), ['유산소'], '띄어쓰기 없어도 잡힌다');
T::is(Parts::of('사이클'), ['유산소'], '사이클 → 유산소');
T::is(Parts::of('준비운동'), ['전신'], '준비운동 → 전신');
T::is(Parts::of('정리운동'), ['전신'], '정리운동 → 전신');

// 한 운동이 두 부위에 걸치면 양쪽에 넣는다(표 순서대로).
T::is(Parts::of('레그 프레스 + 버피'), ['전신', '하체'], '레그 프레스 + 버피 → 전신 · 하체');
T::is(Parts::of('스내치'), ['전신', '어깨'], '스내치 → 전신 · 어깨');

// 공백 차이를 무시한다.
T::is(Parts::of('레그프레스'), ['하체'], '띄어쓰기 없어도 잡힌다');
T::is(Parts::of('렛풀다운'), ['등'], '렛풀다운 = 렛 풀 다운');

// 어느 규칙에도 안 걸리는 것들 — 묶지 않는다.
T::true(Parts::isUnclassified('목표'), '목표는 미분류');
T::true(Parts::isUnclassified('식단 계획'), '식단 계획은 미분류');
T::true(Parts::isUnclassified('운동 계획'), '운동 계획은 미분류');

// 표시 순서 — 몸을 풀고(전신) 유산소로 시작하는 차례가 앞에 온다
T::is(
    Parts::names(),
    ['유산소', '전신', '하체', '등', '가슴', '어깨', '팔', '코어'],
    '부위 표시 순서'
);

// 묶기 — 미분류가 맨 위, 그다음 표 순서
$grouped = Parts::group(['버피', '목표', '스쿼트', '플랭크', '러닝']);
T::is(array_column($grouped, 'part'), ['목표', '유산소', '전신', '하체', '코어'], '미분류가 맨 위에 온다');
T::true($grouped[0]['unclassified'], '첫 항목은 미분류 표시가 붙는다');

T::group('직접 고른 부위 (part_override)');
T::is(Parts::ofExercise('목표', '코어'), ['코어'], '고른 부위가 있으면 그것을 쓴다');
T::is(Parts::ofExercise('스쿼트', '코어'), ['코어'], '이름으로 계산한 것보다 고른 값이 앞선다');
T::is(Parts::ofExercise('스쿼트', null), ['하체'], '고른 값이 없으면 이름에서 계산한다');
T::is(Parts::ofExercise('스쿼트', ''), ['하체'], '빈 값은 없는 것으로 본다');
T::is(Parts::ofExercise('스쿼트', '없는부위'), ['하체'], '표에 없는 부위는 무시한다');
